export function demoReply(text: string, turn: number): string {
  for (const p of PATTERNS) {
    if (p.keywords.some((k) => text.includes(k))) {
      return p.replies[turn % p.replies.length];
    }
  }
  return DEFAULT_REPLIES[turn % DEFAULT_REPLIES.length];
}
